/** Advisor-facing labels. IDs and machine fields remain unchanged in API/audit records. */
const rules: Record<string, string> = {
  PAT_PEER_EQ_FD_DEVIATION: 'Allocation differs from similar investors',
  PAT_MOD_LOW_EQ_FD: 'High fixed-deposit allocation',
  TRUST_UNCERTAIN_TRANSACTION_DATES: 'Transaction dates need verification',
}
export function ruleName(id: string | null | undefined): string {
  if (!id) return 'Portfolio review'
  if (rules[id]) return rules[id]
  if(id.startsWith('MANUAL_'))return 'Advisor-created review'
  if(id.startsWith('PAT_PEER_'))return 'Peer allocation review'
  return id.replace(/^PAT_|^TRUST_/, '').replaceAll('_', ' ').toLowerCase().replace(/^\w/, s => s.toUpperCase())
}
