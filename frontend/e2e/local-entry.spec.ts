import {expect,test} from '@playwright/test'
test('entry button replaces credentials and reports preparation errors',async({page})=>{
 await page.route('**/api/v1/auth/me',r=>r.fulfill({status:401,json:{detail:'Not authenticated'}}))
 await page.route('**/api/v1/auth/enter',r=>r.fulfill({status:503,json:{detail:'Advisor workspace is not prepared. Run SETUP_WINDOWS.bat.'}}))
 await page.goto('/login')
 await expect(page.getByRole('button',{name:'Enter AdviCue'})).toBeVisible()
 await expect(page.locator('input')).toHaveCount(0)
 await page.getByRole('button',{name:'Enter AdviCue'}).click()
 await expect(page.getByRole('alert')).toContainText('SETUP_WINDOWS.bat')
 await page.screenshot({path:'../../../review/local-entry-desktop.png',fullPage:true})
 await page.setViewportSize({width:390,height:844})
 await expect(page.getByRole('button',{name:'Enter AdviCue'})).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
 await page.screenshot({path:'../../../review/local-entry-mobile.png',fullPage:true})
})
