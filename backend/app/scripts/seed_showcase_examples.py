"""Add clearly labeled ILLUSTRATIVE judge records; never claim real advice or AI output.

Run only in local demo mode. Idempotent, does not delete or replace records.
"""
from __future__ import annotations
from datetime import datetime,timezone,date
from sqlalchemy import select


def main():
    from app.core.config import settings
    if not settings.database_url.startswith('sqlite:///') or settings.app_env.lower() not in ('demo','development'):
        print('Illustrative examples skipped outside local SQLite demo mode.')
        return
    from app.core.database import SessionLocal
    from app.models import User,Investor,Holding,LocalAIBrief,MeetingNote,AuditEvent,CommitmentCheck,AdviceRecord,AttentionCase,FollowUpTask
    from app.engines.financial import allocation_for_holdings
    with SessionLocal() as db:
        advisor=db.scalar(select(User).where(User.email=='advisor@advicue.demo',User.role=='ADVISOR'))
        if not advisor:
            print('Demo advisor absent; skipping illustrative notes.')
            return
        inv=db.scalar(select(Investor).where(Investor.id=='INV0009',Investor.advisor_id==advisor.id))
        if not inv:
            inv=db.scalar(select(Investor).where(Investor.advisor_id==advisor.id).order_by(Investor.id))
        if not inv:
            print('Demo advisor has no assigned clients; skipping.');return
        holdings=db.scalars(select(Holding).where(Holding.investor_id==inv.id,Holding.organization_id==advisor.organization_id)).all()
        allocation=allocation_for_holdings(holdings)
        ids=allocation.get('source_row_ids') or []
        if not ids:
            print('No holdings evidence for illustrative examples; skipping.');return
        prefix='ILLUSTRATIVE DEMO EXAMPLE — NOT A RECORD OF AN ACTUAL CLIENT MEETING.'
        existing=db.scalar(select(MeetingNote).where(MeetingNote.investor_id==inv.id,
            MeetingNote.advisor_id==advisor.id,MeetingNote.transcript.startswith(prefix)))
        if not existing:
            now=datetime.now(timezone.utc)
            note=MeetingNote(organization_id=advisor.organization_id,investor_id=inv.id,advisor_id=advisor.id,
                input_method='TEXT',transcript=prefix+' Simulated question: verify approved allocation and future liquidity needs.',
                status='APPROVED',approved_at=now,approved_by=advisor.id,
                approved_summary=prefix+' The advisor would confirm client mandate, horizon and liquidity needs before making a recommendation.',
                approved_commitments=[],approved_preferences={})
            db.add(note);db.flush()
            db.add(AuditEvent(organization_id=advisor.organization_id,actor_id=advisor.id,action='ILLUSTRATIVE_DEMO_NOTE_SEEDED',entity_type='MeetingNote',entity_id=note.id,detail='Clearly labeled fictional sample, not a real client meeting.'))
        brief=db.scalar(select(LocalAIBrief).where(LocalAIBrief.investor_id==inv.id,
                          LocalAIBrief.created_by==advisor.id,LocalAIBrief.model_name=='ILLUSTRATIVE_TEMPLATE_NOT_LLM'))
        if not brief:
            row=LocalAIBrief(organization_id=advisor.organization_id,investor_id=inv.id,
                created_by=advisor.id,model_name='ILLUSTRATIVE_TEMPLATE_NOT_LLM',
                summary='ILLUSTRATIVE DEMO BRIEF — NOT GENERATED BY A LOCAL MODEL. Review the dated portfolio allocation and verify the investor mandate before recommending changes.',
                review_questions=['What investment horizon and liquidity needs did the investor approve?',
                                  'What evidence supports the recorded asset-class weights?'],
                cited_fact_ids=ids[:8],fact_snapshot={'investor_id':inv.id,'allocation':allocation,
                'disclaimer':'Demonstration template, not actual client history, model output, or advice.'})
            db.add(row);db.flush()
            db.add(AuditEvent(organization_id=advisor.organization_id,actor_id=advisor.id,action='ILLUSTRATIVE_DEMO_BRIEF_SEEDED',entity_type='LocalAIBrief',entity_id=row.id,detail='Static fictional example, NOT model-generated.'))
        # An explicitly fictional, historically dated advisor meeting enables the
        # judge to see a real deterministic commitment evaluator operate on later
        # dated sample holdings. It is NOT a claim that such advice ever occurred.
        promise_prefix = 'ILLUSTRATIVE SIMULATED COMMITMENT — NOT A REAL CLIENT MEETING.'
        promise = db.scalar(select(MeetingNote).where(MeetingNote.investor_id==inv.id,
            MeetingNote.advisor_id==advisor.id,MeetingNote.transcript.startswith(promise_prefix)))
        if not promise and allocation.get('as_of_date') and date.fromisoformat(allocation['as_of_date']) >= date(2026,7,31):
            promise = MeetingNote(organization_id=advisor.organization_id,investor_id=inv.id,
                advisor_id=advisor.id,input_method='TEXT',
                transcript=promise_prefix+' Fictional investor agreed to maintain a recorded fixed-deposit share of at least fifty percent until the end of July.',
                status='APPROVED',approved_at=datetime(2026,6,30,tzinfo=timezone.utc),
                approved_by=advisor.id,
                approved_summary=promise_prefix+' Review the fixed-deposit weight using later recorded holdings.',
                approved_commitments=[promise_prefix+' Fixed-deposit allocation at least 50% by 31 July 2026.'],
                approved_preferences={})
            db.add(promise);db.flush()
            db.add(AuditEvent(organization_id=advisor.organization_id,actor_id=advisor.id,
                action='ILLUSTRATIVE_PROMISE_SEEDED',entity_type='MeetingNote',entity_id=promise.id,
                detail='Fully fictional advisor promise, with separately dated sample holdings as evaluator evidence.'))
        if promise and not db.scalar(select(CommitmentCheck).where(CommitmentCheck.meeting_id==promise.id)):
            # An illustration of evaluation logic only, not confirmed client behavior.
            from decimal import Decimal
            db.add(CommitmentCheck(organization_id=advisor.organization_id,investor_id=inv.id,
                advisor_id=advisor.id,meeting_id=promise.id,metric='fixed_deposit_pct',
                comparator='>=',target_pct=Decimal('50'),due_date=date(2026,7,31)))
        # Simulated historical advice is distinguishable from actual investor advice.
        # The post-decision source-reported observations are real rows in the
        # synthetic workbook, but they do NOT show execution or causal improvement.
        advice_prefix='ILLUSTRATIVE SIMULATED HISTORICAL ADVICE — NOT REAL CLIENT ADVICE.'
        demo_case=db.scalar(select(AttentionCase).where(
            AttentionCase.organization_id==advisor.organization_id,
            AttentionCase.investor_id==inv.id,
            AttentionCase.superseded_by_id.is_(None)).order_by(AttentionCase.created_at.desc()))
        seeded_advice=db.scalar(select(AdviceRecord).where(
            AdviceRecord.organization_id==advisor.organization_id,
            AdviceRecord.investor_id==inv.id,
            AdviceRecord.recommendation.startswith(advice_prefix)))
        if demo_case and not seeded_advice:
            historical_decision=datetime(2026,4,15,tzinfo=timezone.utc)
            seeded_advice=AdviceRecord(organization_id=advisor.organization_id,
                investor_id=inv.id,advisor_id=advisor.id,alert_id=demo_case.id,
                status='APPROVED',recommendation=advice_prefix+' Review recorded cash allocation and confirm whether the risk mandate has changed.',
                rationale='ILLUSTRATIVE: A hypothetical decision that uses source-reported data; no historical client instruction is claimed.',
                assumptions='Illustrative record; execution unknown and no portfolio trades inferred.',
                evidence_source_row_ids=ids[:8],created_at=historical_decision,
                submitted_at=historical_decision,decided_at=historical_decision,
                decided_by=advisor.id,decision_note='ILLUSTRATIVE: fictional advisor approval for demonstration of outcome monitoring.',
                expected_outcome='An advisor would seek written confirmation of the client mandate; later allocation and reported benchmark gaps should be reviewed.',
                review_date=date(2026,7,31),review_trigger='Review recorded allocation and reported benchmark gap at next valuation.')
            db.add(seeded_advice);db.flush()
            db.add(AuditEvent(organization_id=advisor.organization_id,actor_id=advisor.id,
                action='ILLUSTRATIVE_HISTORICAL_ADVICE_SEEDED',entity_type='AdviceRecord',
                entity_id=seeded_advice.id,detail='Fictional advice example; not a client recommendation, order or verified execution.'))
        if seeded_advice and not db.scalar(select(FollowUpTask).where(FollowUpTask.advice_id==seeded_advice.id)):
            db.add(FollowUpTask(organization_id=advisor.organization_id,
                investor_id=inv.id,advice_id=seeded_advice.id,owner_id=advisor.id,
                title='ILLUSTRATIVE: verify whether historical advice was actually followed',
                due_date=date(2026,7,31),status='CANNOT_VERIFY',
                completion_note='ILLUSTRATIVE: the dataset cannot establish execution of the hypothetical recommendation.',
                created_at=datetime(2026,4,15,tzinfo=timezone.utc),
                updated_at=datetime(2026,7,31,tzinfo=timezone.utc)))
        db.commit()
        print('Illustrative demo note, brief, commitment and historical advice checked for', inv.id, '(fictional).')

if __name__=='__main__':main()
